#!/usr/bin/env python3
"""The server windows' one look, from one file (design/server-window.tokens.json) into the three places that draw them:

  launcher/ui/hostconsole.css   --sw-* on :root (Dark) and html[data-base="light"] (Light). The neutrals point at the
                                launcher's own --t-* (so theme packs still move them); the frost accent and the console's
                                slate, rows and gold are values.
  stream/admin.py               SW_TOKENS_CSS for Leyline HQ (/wrath/admin): every --sw-* as a value, Light by the
                                system's prefers-color-scheme.
  .../WrathUnleashedUI/Style.lua  S.C and S.HEX, the in-game windows' palette (dark only).
  stream/hub.py                 SITE_TOKENS_CSS for the website (the hub, the forum, the Host page): the --lk-* the site's
                                styles read, Dark by default and Light by the system's prefers-color-scheme, so the site
                                wears the launcher's palette; its accent is the launcher's own blue
                                (style.css --t-accent), read from there.

Each file keeps a marked block (sw-tokens:begin ... sw-tokens:end); only that block is rewritten.

    python3 design/make_tokens.py           write the blocks
    python3 design/make_tokens.py --check   exit 1 when a block is out of date (the tests run this)
"""
import json, os, re, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = os.path.join(ROOT, "design", "server-window.tokens.json")
NOTE = "generated by design/make_tokens.py from design/server-window.tokens.json: edit that file, not this block"
CSS_FILE = os.path.join(ROOT, "launcher", "ui", "hostconsole.css")
PY_FILE = os.path.join(ROOT, "stream", "admin.py")
HUB_FILE = os.path.join(ROOT, "stream", "hub.py")
LUA_FILE = os.path.join(ROOT, "stream", "fui-web", "Interface", "AddOns", "WrathUnleashedUI", "Style.lua")
SKIP = {"glow-alpha", "slate-top", "slate-bottom"}      # folded into --sw-slate / --sw-glow


def load(path=SRC):
    return json.load(open(path, encoding="utf-8"))


def rgba(hex_, a):
    h = hex_.lstrip("#")
    return f"rgba({int(h[0:2], 16)}, {int(h[2:4], 16)}, {int(h[4:6], 16)}, {a})"


def css_vars(t: dict, mode: str, follow: set, launcher: bool) -> list[tuple[str, str]]:
    p = t[mode]
    out = []
    for k, v in p.items():
        if k in SKIP:
            continue
        if launcher and k in follow:
            v = f"var(--t-{k})"
        out.append((k, v))
    out.append(("slate", f"linear-gradient(180deg, {p['slate-top']}, {p['slate-bottom']})"))
    out.append(("glow", f"radial-gradient(120% 80% at 0% 0%, {rgba(p['accent'], p['glow-alpha'])}, transparent 55%), "
                        f"radial-gradient(100% 70% at 100% 100%, {rgba(p['accent-2'], p['glow-alpha'])}, transparent 60%)"))
    if mode == "dark":
        for k, v in t["shape"].items():
            out.append((k, f"var(--t-{k})" if launcher else v))
    return out


def launcher_block(t: dict) -> str:
    follow = set(t["launcher_follows"])
    dark = css_vars(t, "dark", follow, True)
    light = [(k, v) for k, v in css_vars(t, "light", follow, True) if not v.startswith("var(--t-")]
    body = "\n".join(f"  --sw-{k}: {v};" for k, v in dark)
    lbody = "\n".join(f"  --sw-{k}: {v};" for k, v in light)
    return f"/* sw-tokens:begin: {NOTE} */\n:root {{\n{body}\n}}\nhtml[data-base=\"light\"] {{\n{lbody}\n}}\n/* sw-tokens:end */"


def web_block(t: dict) -> str:
    def flat(pairs):
        return ";".join(f"--sw-{k}:{v.replace(', ', ',')}" for k, v in pairs)
    dark = css_vars(t, "dark", set(), False)
    light = css_vars(t, "light", set(), False)
    light = [(k, v) for k, v in light if k not in t["shape"]]
    css = f":root{{{flat(dark)};color-scheme:dark}}\n@media (prefers-color-scheme:light){{:root{{{flat(light)};color-scheme:light}}}}"
    return f"# sw-tokens:begin: {NOTE}\nSW_TOKENS_CSS = \"\"\"\n{css}\n\"\"\"\n# sw-tokens:end"


# The website's names (stream/hub.py HUB_CSS reads --lk-*) for the tokens: (site name, token)
SITE_NAMES = (("bg", "bg"), ("chrome", "chrome"), ("surface", "surface"), ("surface-2", "surface-2"), ("raised", "raised"),
              ("border", "border"), ("border-strong", "border-strong"), ("text", "text"), ("text-2", "text-2"),
              ("muted", "muted"), ("accent", "accent"), ("accent-strong", "accent-strong"), ("accent-press", "accent-press"),
              ("on-accent", "on-accent"), ("accent-soft", "accent-soft"), ("accent-2", "accent-2"), ("ok", "ok"),
              ("warn", "warn"), ("bad", "bad"), ("danger", "danger"), ("gold", "gold-text"), ("gold-line", "gold-line"))


STYLE_FILE = os.path.join(ROOT, "launcher", "ui", "style.css")
SITE_ACCENT = ("accent", "accent-strong", "accent-soft", "on-accent")   # the launcher's own blue (owner 2026-10-31), not frost


def launcher_accent() -> dict:
    """The launcher's accent tokens (style.css --t-*), Dark from its first :where(:root) block, Light from
    :where(html[data-base="light"])."""
    css = open(STYLE_FILE, encoding="utf-8").read()
    out = {}
    for mode, sel in (("dark", r":where\(:root\)"), ("light", r':where\(html\[data-base="light"\]\)')):
        m = re.search(sel + r"\s*\{(.*?)\}", css, re.S)
        body = m.group(1) if m else ""
        out[mode] = {k: v.strip() for k in SITE_ACCENT
                     for v in re.findall(rf"--t-{re.escape(k)}:\s*([^;]+);", body)[:1]}
    return out


def site_block(t: dict) -> str:
    acc = launcher_accent()

    def flat(mode):
        p = dict(t[mode])
        p.update(acc.get(mode, {}))
        if acc.get(mode, {}).get("accent"):
            p["accent-press"] = f"color-mix(in srgb, {p['accent']} 82%, #000)"
        return ";".join(f"--lk-{k}:{p[v].replace(', ', ',')}" for k, v in SITE_NAMES)
    sh = t["shape"]
    shape = f"--lk-r:{sh['radius']};--lk-r-sm:{sh['radius-sm']};--lk-r-xs:{sh['radius-xs']};--lk-font:{sh['font']}"
    css = (f":root{{{flat('dark')};{shape};color-scheme:dark}}\n"
           f"@media (prefers-color-scheme:light){{:root{{{flat('light')};color-scheme:light}}}}")
    return f"# sw-tokens:begin: {NOTE}\nSITE_TOKENS_CSS = \"\"\"\n{css}\n\"\"\"\n# sw-tokens:end"


def lua_block(t: dict) -> str:
    dark, g = t["dark"], t["game"]
    rows = []
    for k, ref in g["C"].items():
        name, a = (ref, None) if isinstance(ref, str) else (ref[0], ref[1])
        hx = dark[name].lstrip("#").lower()
        rows.append(f'    {k} = rgb("{hx}"{", " + str(a) if a is not None else ""}),   -- {name}')
    hexes = ", ".join(f'{k} = "{dark[v].lstrip("#").lower()}"' for k, v in g["HEX"].items())
    return (f"-- sw-tokens:begin: {NOTE}\nS.C = {{\n" + "\n".join(rows) + f"\n}}\nS.HEX = {{ {hexes} }}\n-- sw-tokens:end")


BLOCKS = [
    (CSS_FILE, re.compile(r"/\* sw-tokens:begin.*?/\* sw-tokens:end \*/", re.S), launcher_block),
    (PY_FILE, re.compile(r"# sw-tokens:begin.*?# sw-tokens:end", re.S), web_block),
    (LUA_FILE, re.compile(r"-- sw-tokens:begin.*?-- sw-tokens:end", re.S), lua_block),
    (HUB_FILE, re.compile(r"# sw-tokens:begin.*?# sw-tokens:end", re.S), site_block),
]


def run(check: bool) -> int:
    t = load()
    stale = []
    for path, rx, make in BLOCKS:
        text = open(path, encoding="utf-8").read()
        m = rx.search(text)
        if not m:
            print(f"no sw-tokens block in {os.path.relpath(path, ROOT)}")
            return 2
        want = make(t)
        if m.group(0) != want:
            stale.append(os.path.relpath(path, ROOT))
            if not check:
                open(path, "w", encoding="utf-8", newline="\n").write(text[:m.start()] + want + text[m.end():])
    if check and stale:
        print("out of date (run python3 design/make_tokens.py): " + ", ".join(stale))
        return 1
    print(("up to date" if check else "written: " + (", ".join(stale) or "nothing changed")))
    return 0


if __name__ == "__main__":
    sys.exit(run("--check" in sys.argv[1:]))
