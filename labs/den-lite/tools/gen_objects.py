#!/usr/bin/env python3
"""Makes src/objects.rs: the gameobject entries Den Lite can show, with their type, display id, name and size.

Entries: every catalog prop of realm/custom/lua_scripts/ov_build.lua (CATALOG and the buildings list), the room looks
of ov_den.lua (THEMES), the stamp marker, and every entry in den-stamps/ and den-starters/. Their rows come from
AzerothCore's world database, table gameobject_template (data/sql/base/db_world/gameobject_template.sql, or a
mysqldump of acore_world). Nothing from the game's own files is used.

    python3 -I tools/gen_objects.py <repo root> <gameobject_template dump .sql>  > src/objects.rs
"""
import glob, json, re, sys

root, dump = sys.argv[1], sys.argv[2]
lua = root + "/realm/custom/lua_scripts"
ents = set()
src = open(lua + "/ov_build.lua", encoding="utf8").read()
cat = src[src.index("local CATALOG = {"):]
cat = cat[:cat.index("\n}\n")]
ents |= {int(m) for m in re.findall(r"\{ id = (\d+),", cat)}
blds = src[src.index("for _, b in ipairs({"):]
blds = blds[:blds.index("}) do")]
ents |= {int(m) for m in re.findall(r"\{ (\d+), \"", blds)}
den = open(lua + "/ov_den.lua", encoding="utf8").read()
th = den[den.index("local THEMES = {"):]
th = th[:th.index("\n}\n")]
ents |= {int(m) for m in re.findall(r"(?:floor|wall|light) = (\d+)", th)}
ents.add(180007)   # Excavation Stake: the stamp mark (ov_den_home.lua H.MARKER)
for f in glob.glob(lua + "/den-stamps/*.den.json") + glob.glob(lua + "/den-starters/*.den.json"):
    for p in json.load(open(f, encoding="utf8"))["props"]:
        if p["entry"] < 2000000000:
            ents.add(p["entry"])

row = re.compile(r"^\((\d+),(\d+),(\d+),'((?:[^'\\]|\\.)*)','(?:[^'\\]|\\.)*','(?:[^'\\]|\\.)*','(?:[^'\\]|\\.)*',([\d.eE+-]+),")
rows = {}
for line in open(dump, encoding="utf8"):
    m = row.match(line)
    if m and int(m.group(1)) in ents:
        name = m.group(4).replace("\\'", "'").replace('"', "")
        rows[int(m.group(1))] = (int(m.group(2)), int(m.group(3)), name, float(m.group(5)))
missing = sorted(ents - rows.keys())
print("//! Generated by tools/gen_objects.py: do not edit by hand.")
print("//!")
print("//! The gameobject entries Den Lite knows: (entry, type, display id, name, size). Taken from AzerothCore's world")
print("//! database, `gameobject_template` (columns `entry`, `type`, `displayId`, `name`, `size`; build 12340 rows), for")
print("//! every catalog prop of `ov_build.lua`, the room looks of `ov_den.lua`, the stamp marker and every entry in")
print("//! `den-stamps/` and `den-starters/`.")
if missing:
    print("//! Not in that table (left out): " + ", ".join(map(str, missing)) + ".")
print()
print("pub const OBJECTS: &[(u32, u8, u32, &str, f32)] = &[")
for e in sorted(rows):
    t, d, n, s = rows[e]
    print(f'    ({e}, {t}, {d}, "{n}", {s!r}),')
print("];")
