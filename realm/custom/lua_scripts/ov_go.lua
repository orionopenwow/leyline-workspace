-- ov_go.lua: go anywhere from the website (mod-ale, 3.3.5a).
--
-- The Modes hub (https://play.openvanilla.app/wrath/modes, stream/modes.py) has one link per duel spot, raid,
-- raid wing, dungeon, random queue and hangout. A signed-in player who follows one arrives with ?go=<kind>:<id>,
-- and the portal (stream/wrath_portal.py remember_go) records it for that game account over SOAP:
--     ovgo set <ACCOUNT> <kind>:<id>          ovgo clear <ACCOUNT>          (console / SOAP only)
-- The reply starts "ovgo ok" when it was taken. Then, on that account's next login (or at once if a character
-- is online), this script:
--   * dungeons, raids, raid wings and hangouts: teleports the character to the door (the spot just inside the
--     instance, AzerothCore's areatrigger_teleport target) or the hangout, when its level is high enough;
--     a raid needs a raid group first (the core's own rule), a wing goes to its raid's door with a line on
--     how to reach the wing;
--   * random queues: says how to queue (mod-ale has no call that queues a player for the Dungeon Finder);
--   * refuses in combat, while dead, inside an instance, a battleground or an arena, and keeps the intent:
--     .go tries again, .go cancel forgets it. An intent expires 30 minutes after it was set, and is used once.
--   * a character below the level waits: reaching the level (the boost to 80 included) tries again by itself,
--     and another character of the account can use it. A brand new character is never moved during its first
--     login (it picks boost or level 1 first): .go, or the level-up, does it.
-- Only places in PLACES below can be reached: the table is generated from stream/modes_data.py (map ids,
-- entrances, levels and where each number came from are documented there). A place with no entrance in that
-- file is looked up in the world database's areatrigger_teleport by its map.
-- Browser (streamed) accounts stay inside the stream: ov_slices.lua brings them home from a place that isn't
-- streamed, with its own message.
--
-- .hub (also .wuhub): the Dalaran spots for the modes players can't find otherwise: the duel corner, the 1v1 arena
-- battlemaster, the transmogrifier and the keystone master (their NPCs are spawned by realm/serverpass.sh step 2b,
-- at the HUB positions below; stream/tests/test_ov_go_hub.lua keeps the two in step), and how Hardcore starts.
-- .hub <spot> hops there when you are already in Dalaran (out of combat, every 10 s); from elsewhere it says where.
-- ov_qol.lua's own travel hubs (.hub gurubashi etc., on the Brawl and Dalaran profiles) keep their names.
--
-- Player commands: .go (try the waiting go now; also .wugo), .go cancel. Plain players only for .go, so a GM's
-- own .go commands are never shadowed; .wugo works for everyone. Players can never use ovgo: the console
-- command is only read when the command hook has no player (the console or SOAP).
-- Table (auth DB, created here): ov_go_intents (account_id, go, expires_at), so an intent survives a restart.
-- mod-ale events: 3 ON_LOGIN, 13 ON_LEVEL_CHANGE, 30 ON_FIRST_LOGIN, 42 ON_COMMAND (return false = handled).
-- API: AuthDBQuery / AuthDBExecute, WorldDBQuery, GetPlayersInWorld, Player:Teleport(map, x, y, z, o) (false when
-- the core refuses), Player:GetAccountId, Unit:GetLevel, Unit:IsInCombat, Unit:IsDead, Player:InBattleground,
-- Player:InArena, WorldObject:GetMap + Map:IsDungeon/IsRaid/IsBattlegroundOrArena, Player:GetGroup +
-- Group:IsRaidGroup, Player:GetGMRank, WorldObject:RegisterEvent(fn, delay, repeats).

