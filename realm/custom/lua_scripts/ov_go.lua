local function say(player, text) player:SendBroadcastMessage(TAG .. text) end

local function try(obj, method, ...)
    if not obj then return nil end
    local ok, fn = pcall(function() return obj[method] end)
    if not ok or type(fn) ~= "function" then return nil end
    local ok2, a = pcall(fn, obj, ...)
    if ok2 then return a end
    return nil
end

AuthDBExecute("CREATE TABLE IF NOT EXISTS ov_go_intents ("
    .. "account_id INT UNSIGNED NOT NULL PRIMARY KEY, go VARCHAR(40) NOT NULL, "
    .. "expires_at INT UNSIGNED NOT NULL, KEY expires_at (expires_at))")

local function validGo(go)
    return type(go) == "string" and #go <= 40 and go:match("^[hqb]:[%l%d][%l%d%-]*$") ~= nil and PLACES[go] ~= nil
end

local function forget(accountId)
    pending[accountId] = nil
    AuthDBExecute(string.format("DELETE FROM ov_go_intents WHERE account_id = %d", accountId))
end

-- The waiting intent of an account: this process's own, else the auth DB's (set before a restart).
local function pendingOf(accountId)
    local g = pending[accountId]
    if not g then
        local q = AuthDBQuery(string.format(
            "SELECT go, expires_at - UNIX_TIMESTAMP() FROM ov_go_intents WHERE account_id = %d "
            .. "AND expires_at > UNIX_TIMESTAMP()", accountId))
        if q then
            local go, left = q:GetString(0), q:GetInt32(1)
            if validGo(go) and left > 0 then
                g = { go = go, exp = now() + math.min(left, TTL) }
                pending[accountId] = g
            end
        end
    end
    if g and g.exp <= now() then
        forget(accountId)
        return nil
    end
    return g
end

local function blocked(player)
    if try(player, "IsInCombat") then return "not in combat" end
    if try(player, "IsDead") then return "not while dead" end
    if try(player, "InBattleground") or try(player, "InArena") then return "not from a battleground or arena" end
    local map = try(player, "GetMap")
    if map and (try(map, "IsBattlegroundOrArena") or try(map, "IsDungeon") or try(map, "IsRaid")) then
        return "not from inside an instance"
    end
    return nil
end

local function door(p)
    if p.pos then return p.pos end
    if not p.map then return nil end
    if doors[p.map] == nil then
        doors[p.map] = false
        local q = WorldDBQuery(string.format(
            "SELECT target_map, target_position_x, target_position_y, target_position_z, target_orientation "
            .. "FROM areatrigger_teleport WHERE target_map = %d ORDER BY ID LIMIT 1", p.map))
        if q then doors[p.map] = { q:GetUInt32(0), q:GetFloat(1), q:GetFloat(2), q:GetFloat(3), q:GetFloat(4) } end
    end
    return doors[p.map] or nil
end

local function minutesLeft(g) return math.max(1, math.ceil((g.exp - now()) / 60)) end

-- Try the account's waiting go with this character. why: "login", "level", "set", "command".
local function act(player, why)
    local account = player:GetAccountId()
    local g = pendingOf(account)
    if not g then
        if why == "command" then say(player, "Nothing is waiting. Pick a place on " .. SITE .. ", then come back.") end
        return
    end
    local p = PLACES[g.go]
    if not p then forget(account); return end
    local lvl = player:GetLevel()
    if p.what == "queue" then
        forget(account)
        if lvl < p.min then
            say(player, p.name .. " opens at level " .. p.min .. ".")
            return
        end
        say(player, p.name .. ": press |cffffff00I|r (or the eye by the minimap), choose it in the Dungeon Finder, "
            .. "pick your role and Find Group. Bots fill the empty places.")
        return
    end
    if lvl < p.min then
        if why ~= "level" then
            say(player, string.format("%s needs level %d. Reach it (new characters: |cffffff00.boost|r) or log in a "
                .. "character of level %d in the next %d min, and Go takes you there.", p.name, p.min, p.min, minutesLeft(g)))
        end
        return
    end
    if why == "login" and fresh[player:GetGUIDLow()] then
        say(player, "Waiting for you: " .. p.name .. ". Type |cffffff00.go|r when you're ready.")
        return
    end
    local stop = blocked(player)
    if stop then
        say(player, "Go to " .. p.name .. ": " .. stop .. ". Type |cffffff00.go|r when you're free (|cffffff00.go cancel|r forgets it).")
        return
    end
    if p.raid then
        local group = try(player, "GetGroup")
        if not (group and try(group, "IsRaidGroup")) then
            say(player, p.name .. " is a raid: form a raid group first (Party > Convert to Raid works with one friend), "
                .. "then type |cffffff00.go|r.")
            return
        end
    end
    local pos = door(p)
    if not pos then
        forget(account)
        say(player, "There's no entrance on file for " .. p.name .. " yet. Sorry!")
        return
    end
    forget(account)   -- used once, whatever the core says next
    say(player, "Taking you to " .. p.name .. ".")
    if player:Teleport(pos[1], pos[2], pos[3], pos[4], pos[5]) == false then
        say(player, "You can't enter " .. p.name .. " yet (level, key, lockout or group rule).")
        return
    end
    if p.hint and p.hint ~= "" then say(player, p.hint) end
end

-- Deferred: never teleport from inside a login, level or command hook.
local function later(player, delay, why)
    local guid = player:GetGUIDLow()
    if queued[guid] then return end
    queued[guid] = true
    player:RegisterEvent(function(_, _, _, p)
        queued[guid] = nil
        act(p, why)
    end, delay, 1)
end

local function onlineByAccount(accountId)
    for _, p in ipairs(GetPlayersInWorld() or {}) do
        if p:GetAccountId() == accountId then return p end
    end
end

-- console: ovgo set <ACCOUNT> <kind>:<id> | ovgo clear <ACCOUNT>
local function consoleCommand(command, handler)
    local verb, rest = command:match("^ovgo%s+(%a+)%s*(.*)$")
    if not verb then return nil end
    local function reply(msg) if handler then handler:SendSysMessage(msg) end end
    local name, go
    if verb == "set" then
        name, go = rest:match("^(%w+)%s+(%S+)%s*$")
    elseif verb == "clear" then
        name = rest:match("^(%w+)%s*$")
    end
    if not name or #name > 16 or (verb == "set" and not validGo(go)) then
        reply("ovgo: usage: ovgo set <account> <kind>:<id> (a place from the Modes hub) | ovgo clear <account>")
        return false
    end
    name = name:upper()
    local q = AuthDBQuery(string.format("SELECT id FROM account WHERE username = '%s'", name))
    if not q then
        reply("ovgo: no such account " .. name)
        return false
    end
    local id = q:GetUInt32(0)
    if verb == "set" then
        AuthDBExecute(string.format("REPLACE INTO ov_go_intents (account_id, go, expires_at) "
            .. "VALUES (%d, '%s', UNIX_TIMESTAMP() + %d)", id, go, TTL))
        pending[id] = { go = go, exp = now() + TTL }
        local p = onlineByAccount(id)
        if p then later(p, 250, "set") end
        reply(string.format("ovgo ok: %s -> %s (%d min)%s", name, go, TTL / 60, p and ", online now" or ""))
    else
        forget(id)
        reply("ovgo ok: " .. name .. " cleared")
    end
    return false
end

