#!/usr/bin/env python3
"""Boss fight heroes: the kit and bar data for the C++ module, made from the realm's own Lua data so both stay one.

    python3 realm/custom/modules/mod-leyline-bossfights/tools/gen_hero_data.py          # write the header
    python3 realm/custom/modules/mod-leyline-bossfights/tools/gen_hero_data.py --check  # exit 1 if it is stale

Reads (never writes):
    realm/custom/lua_scripts/ov_kits.lua   OV_KITS (GENERATED by gen_kits.py): per class and spec the PvE and PvP kits
    realm/custom/lua_scripts/ov_main.lua   the boost's tables: BARS (action bar layouts), WEAPON_SPELLS, QUEST_SPELLS,
                                           CLASS_ITEMS, FACTION_ONLY, RACIALS
Writes:
    realm/custom/modules/mod-leyline-bossfights/src/BossfightsHeroData.h   (GENERATED: change the Lua, then run this)

A bar slot is a list of alternatives: a spell id (rank 1; the module puts the highest rank the hero knows), 0 for
empty, or one of the boost's markers as a negative number: -1 RACIAL, -2 HEARTH, -3 PVP (the PvP medallion), -4 GROUND,
-5 FLY. Heroes have no hearthstone and no mounts, so the module leaves -2, -4 and -5 for its own items (flask, food).
Standard library only. The Lua reader understands only what these files use: table constructors, numbers, strings,
names of the boost's locals, and comments.
"""
from __future__ import annotations

import os
import re
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
MODULE = os.path.dirname(HERE)
CUSTOM = os.path.dirname(os.path.dirname(MODULE))
KITS_LUA = os.path.join(CUSTOM, "lua_scripts", "ov_kits.lua")
MAIN_LUA = os.path.join(CUSTOM, "lua_scripts", "ov_main.lua")
OUT = os.path.join(MODULE, "src", "BossfightsHeroData.h")

MARKERS = {"RACIAL": -1, "HEARTH": -2, "PVP": -3, "GROUND": -4, "FLY": -5}


class LuaError(ValueError):
    pass


TOKEN = re.compile(r"""\s+|--\[\[.*?\]\]|--[^\n]*|(?P<num>-?\d+(?:\.\d+)?)|(?P<str>"(?:[^"\\]|\\.)*")|(?P<name>[A-Za-z_][A-Za-z0-9_]*)|(?P<p>[{}\[\]=,;])""", re.S)


def tokens(text: str):
    pos, out = 0, []
    while pos < len(text):
        m = TOKEN.match(text, pos)
        if not m:
            raise LuaError(f"can't read Lua at {text[pos:pos + 40]!r}")
        pos = m.end()
        if m.group("num") is not None:
            out.append(("num", m.group("num")))
        elif m.group("str") is not None:
            out.append(("str", bytes(m.group("str")[1:-1], "utf-8").decode("unicode_escape")))
        elif m.group("name") is not None:
            out.append(("name", m.group("name")))
        elif m.group("p") is not None:
            out.append(("p", m.group("p")))
    return out


def parse_expr(toks, i, env):
    """(value, next index): a table becomes {"list": [...], "map": {key: value}}."""
    kind, v = toks[i]
    if kind == "num":
        return (float(v) if "." in v else int(v)), i + 1
    if kind == "str":
        return v, i + 1
    if kind == "name":
        if v in ("true", "false"):
            return v == "true", i + 1
        if v not in env:
            raise LuaError(f"unknown name {v}")
        return env[v], i + 1
    if kind == "p" and v == "{":
        return parse_table(toks, i + 1, env)
    raise LuaError(f"unexpected {v!r}")


def parse_table(toks, i, env):
    t = {"list": [], "map": {}}
    while True:
        kind, v = toks[i]
        if kind == "p" and v == "}":
            return t, i + 1
        if kind == "p" and v == "[":
            key, i = parse_expr(toks, i + 1, env)
            if toks[i] != ("p", "]") or toks[i + 1] != ("p", "="):
                raise LuaError("bad [key] =")
            val, i = parse_expr(toks, i + 2, env)
            t["map"][key] = val
        elif kind == "name" and toks[i + 1] == ("p", "="):
            val, i = parse_expr(toks, i + 2, env)
            t["map"][v] = val
        else:
            val, i = parse_expr(toks, i, env)
            t["list"].append(val)
        if toks[i][0] == "p" and toks[i][1] in (",", ";"):
            i += 1


def matching_brace(text: str, start: int) -> int:
    """The index of the "}" that closes the "{" at start (strings and comments skipped)."""
    depth, i = 0, start
    while i < len(text):
        c = text[i]
        if c == '"':
            i += 1
            while text[i] != '"':
                i += 2 if text[i] == "\\" else 1
        elif text.startswith("--", i):
            i = text.find("\n", i)
            if i < 0:
                break
        elif c == "{":
            depth += 1
        elif c == "}":
            depth -= 1
            if depth == 0:
                return i
        i += 1
    raise LuaError("unclosed table")


def table_after(text: str, anchor: str, env) -> dict:
    """The table constructor that follows `anchor` (a regex) in text."""
    m = re.search(anchor, text)
    if not m:
        raise LuaError(f"{anchor!r} not found")
    start = text.index("{", m.end() - 1)
    toks = tokens(text[start:matching_brace(text, start) + 1])
    val, _ = parse_expr(toks, 0, env)
    return val


def ids(t) -> list[int]:
    return [int(x) for x in t["list"]]


def read_kits(text: str) -> tuple[list, dict]:
    kits = table_after(text, r"OV_KITS\s*=\s*\{", {})
    med = kits["map"]["MEDALLION"]["map"]
    order = kits["map"]["order"]["map"]
    out = []
    for cls in sorted(k for k in kits["map"] if isinstance(k, int)):
        specs = kits["map"][cls]["map"]
        for key in order[cls]["list"]:
            s = specs[key]["map"]
            out.append({"cls": cls, "key": key, "name": s["name"], "role": s["role"],
                        "pve": ids(s["pve"]), "pvp": ids(s["pvp"])})
    return out, {"alliance": int(med["alliance"]), "horde": int(med["horde"])}


def slot(v) -> list[int]:
    if isinstance(v, dict):
        return [slot(x)[0] for x in v["list"]]
    if isinstance(v, str):
        if v.upper() not in MARKERS:
            raise LuaError(f"unknown bar marker {v}")
        return [MARKERS[v.upper()]]
    return [int(v)]


def read_main(text: str) -> dict:
    env = {k: k.lower() for k in MARKERS}
    env["SEAL_VC"] = table_after(text, r"local SEAL_VC\s*=\s*\{", env)
    env["HEROISM"] = table_after(text, r"local HEROISM\s*=\s*\{", env)
    env["MAGE_PORTS"] = table_after(text, r"local MAGE_PORTS\s*=\s*\{", env)
    bars = []
    for m in re.finditer(r"^BARS\[(\d+)\]\s*=\s*\{", text, re.M):
        cls = int(m.group(1))
        t = table_after(text[m.start():], r"BARS\[\d+\]\s*=\s*\{", env)
        for spec, rows in t["map"].items():
            for start, row in rows["map"].items():
                bars.append({"cls": cls, "spec": "" if spec == "base" else spec, "start": int(start),
                             "slots": [slot(x) for x in row["list"]]})
    weapon = table_after(text, r"local WEAPON_SPELLS\s*=\s*\{", env)
    quest = table_after(text, r"local QUEST_SPELLS\s*=\s*\{", env)
    items = table_after(text, r"local CLASS_ITEMS\s*=\s*\{", env)
    racials = table_after(text, r"local RACIALS\s*=\s*\{", env)
    faction = {"alliance": [], "horde": []}
    for m in re.finditer(r"for _, id in ipairs\(\{([^}]*)\}\) do FACTION_ONLY\[id\] = TEAM_(ALLIANCE|HORDE)", text):
        faction[m.group(2).lower()] += [int(x) for x in re.findall(r"\d+", m.group(1))]
    bag = re.search(r"local BAG\s*=\s*(\d+)", text)
    return {
        "bars": bars,
        "weapon": {int(k): ids(v) for k, v in weapon["map"].items()},
        "quest": {int(k): ids(v) for k, v in quest["map"].items()},
        "items": {int(k): [(int(p["list"][0]), int(p["list"][1])) for p in v["list"]] for k, v in items["map"].items()},
        "racials": ids(racials),
        "faction": faction,
        "bag": int(bag.group(1)) if bag else 41599,
    }


def cpp_list(xs) -> str:
    return "{ " + ", ".join(str(x) for x in xs) + " }" if xs else "{}"


def render(kits, med, main) -> str:
    L = []
    w = L.append
    w("// GENERATED by realm/custom/modules/mod-leyline-bossfights/tools/gen_hero_data.py from")
    w("// realm/custom/lua_scripts/ov_kits.lua (the kits) and ov_main.lua (the boost's bars and class tables).")
    w("// Do not edit by hand: change the Lua (or the generator) and run it again. Pure data, no core headers.")
    w("#ifndef LEYLINE_BOSSFIGHTS_HERO_DATA_H")
    w("#define LEYLINE_BOSSFIGHTS_HERO_DATA_H")
    w("")
    w("#include <cstdint>")
    w("#include <utility>")
    w("#include <vector>")
    w("")
    w("namespace LeylineBF")
    w("{")
    w("    struct HeroKit")
    w("    {")
    w("        std::uint8_t cls;")
    w("        char const* key;      // ov_kits.lua spec key (\"all\" for the shared mage / warlock kit)")
    w("        char const* name;")
    w("        char const* role;     // the generator's stat profile")
    w("        std::vector<std::uint32_t> pve;")
    w("        std::vector<std::uint32_t> pvp;")
    w("    };")
    w("")
    w(f"    constexpr std::uint32_t HERO_MEDALLION_ALLIANCE = {med['alliance']};")
    w(f"    constexpr std::uint32_t HERO_MEDALLION_HORDE = {med['horde']};")
    w(f"    constexpr std::uint32_t HERO_BAG = {main['bag']};")
    w("    constexpr std::int32_t BAR_RACIAL = -1, BAR_HEARTH = -2, BAR_PVP = -3, BAR_GROUND = -4, BAR_FLY = -5;")
    w("")
    w("    inline std::vector<HeroKit> const& HeroKits()")
    w("    {")
    w("        static std::vector<HeroKit> const kits = {")
    for k in kits:
        w(f'            {{ {k["cls"]}, "{k["key"]}", "{k["name"]}", "{k["role"]}",')
        w(f"              {cpp_list(k['pve'])},")
        w(f"              {cpp_list(k['pvp'])} }},")
    w("        };")
    w("        return kits;")
    w("    }")
    w("")
    w("    // A bar row: the class, the spec key (\"\" = every spec of the class), the first button and its slots.")
    w("    struct HeroBarRow")
    w("    {")
    w("        std::uint8_t cls;")
    w("        char const* spec;")
    w("        std::uint8_t start;")
    w("        std::vector<std::vector<std::int32_t>> slots;")
    w("    };")
    w("")
    w("    inline std::vector<HeroBarRow> const& HeroBarRows()")
    w("    {")
    w("        static std::vector<HeroBarRow> const rows = {")
    for r in main["bars"]:
        slots = ", ".join(cpp_list(s) for s in r["slots"])
        w(f'            {{ {r["cls"]}, "{r["spec"]}", {r["start"]}, {{ {slots} }} }},')
    w("        };")
    w("        return rows;")
    w("    }")
    w("")

    def by_class(name, d, fmt):
        w(f"    inline std::vector<{fmt}> const& {name}(std::uint8_t cls)")
        w("    {")
        w(f"        static std::vector<{fmt}> const none;")
        w("        switch (cls)")
        w("        {")
        for c in sorted(d):
            w(f"            case {c}: {{ static std::vector<{fmt}> const v = {cpp_list(d[c]) if fmt == 'std::uint32_t' else '{ ' + ', '.join('{ %d, %d }' % p for p in d[c]) + ' }'}; return v; }}")
        w("            default: return none;")
        w("        }")
        w("    }")
        w("")

    by_class("HeroWeaponSpells", main["weapon"], "std::uint32_t")
    by_class("HeroQuestSpells", main["quest"], "std::uint32_t")
    by_class("HeroClassItems", main["items"], "std::pair<std::uint32_t, std::uint32_t>")
    w(f"    inline std::vector<std::uint32_t> const& HeroRacials() {{ static std::vector<std::uint32_t> const v = {cpp_list(main['racials'])}; return v; }}")
    w(f"    inline std::vector<std::uint32_t> const& HeroAllianceOnly() {{ static std::vector<std::uint32_t> const v = {cpp_list(main['faction']['alliance'])}; return v; }}")
    w(f"    inline std::vector<std::uint32_t> const& HeroHordeOnly() {{ static std::vector<std::uint32_t> const v = {cpp_list(main['faction']['horde'])}; return v; }}")
    w("}")
    w("")
    w("#endif")
    return "\n".join(L) + "\n"


def build() -> str:
    with open(KITS_LUA, encoding="utf-8") as f:
        kits, med = read_kits(f.read())
    with open(MAIN_LUA, encoding="utf-8") as f:
        main = read_main(f.read())
    return render(kits, med, main)


def main(argv) -> int:
    text = build()
    if "--check" in argv:
        try:
            with open(OUT, encoding="utf-8") as f:
                same = f.read() == text
        except OSError:
            same = False
        print("BossfightsHeroData.h is " + ("up to date" if same else "STALE: run gen_hero_data.py"))
        return 0 if same else 1
    with open(OUT, "w", encoding="utf-8") as f:
        f.write(text)
    print(f"wrote {os.path.relpath(OUT, CUSTOM)} ({text.count(chr(10))} lines)")
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
