#!/usr/bin/env python3
"""Make ov_slices_lfg.lua: the Dungeon Finder id -> map table ov_slices.lua uses to let stream
players queue only for streamed dungeons.

    python3 -I lfg_ids.py <LFGDungeons.dbc or http://127.0.0.1:8090/data/...> > ov_slices_lfg.lua

The input is the client's own DBFilesClient\\LFGDungeons.dbc: after --export it is in the slice
folder (<slice>/DBFilesClient/LFGDungeons.dbc), or fetch it from a running local wenilla-host.
3.3.5a layout (AzerothCore DBCfmt.h LFGDungeonEntryfmt, DBCStructure.h): field 0 ID, 18 MinLevel,
19 MaxLevel, 23 MapID, 26 TypeID. Random dungeons (TypeID 6) are left out, so ov_slices.lua refuses
them: the server picks their map. OV_STREAM_LFG_LEVEL holds each entry's level range, so a stream
character is only offered the streamed dungeons of its level.
"""
import struct
import sys
import urllib.request

RANDOM_TYPE = 6
F_ID, F_MIN, F_MAX, F_MAP, F_TYPE = 0, 18, 19, 23, 26


def rows(dbc: bytes):
    if dbc[:4] != b"WDBC":
        raise ValueError("not a WDBC file")
    records, fields, size, _strings = struct.unpack_from("<4I", dbc, 4)
    if fields <= F_TYPE or size < fields * 4:
        raise ValueError(f"unexpected LFGDungeons layout ({fields} fields)")
    for r in range(records):
        row = struct.unpack_from(f"<{fields}i", dbc, 20 + r * size)
        if row[F_TYPE] != RANDOM_TYPE and row[F_MAP] >= 0:
            yield row


def parse(dbc: bytes) -> dict[int, int]:
    """Dungeon Finder id -> map id (random entries left out)."""
    return {row[F_ID]: row[F_MAP] for row in rows(dbc)}


def parse_levels(dbc: bytes) -> dict[int, tuple[int, int]]:
    """Dungeon Finder id -> (min level, max level)."""
    return {row[F_ID]: (row[F_MIN], row[F_MAX]) for row in rows(dbc)}


def lua(table: dict[int, int], levels: dict[int, tuple[int, int]] | None = None) -> str:
    lines = ["-- Generated by lfg_ids.py from the client's LFGDungeons.dbc: Dungeon Finder id -> map.",
             "-- ov_slices.lua reads it to let stream players queue only for streamed dungeons.",
             "OV_STREAM_LFG = {"]
    lines += [f"    [{k}] = {v}," for k, v in sorted(table.items())]
    lines.append("}")
    if levels:
        lines.append("OV_STREAM_LFG_LEVEL = {")
        lines += [f"    [{k}] = {{ {lo}, {hi} }}," for k, (lo, hi) in sorted(levels.items())]
        lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    if len(argv) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    src = argv[0]
    if src.startswith("http://") or src.startswith("https://"):
        with urllib.request.urlopen(src, timeout=30) as r:
            data = r.read()
    else:
        with open(src, "rb") as f:
            data = f.read()
    sys.stdout.write(lua(parse(data), parse_levels(data)))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
