#!/usr/bin/env python3
"""Make ov_slices_tiers.lua: the slice's tiers (from slices/<slice>.json) for the realm rule.

    python3 -I tiers_lua.py slices/mini.json > ov_slices_tiers.lua

ov_slices.lua reads the global OV_STREAM_TIERS this writes, so the tier list lives in one place
(mini.json): reorder its "order" list, run stream-up.sh or upload the slice again, and the realm
follows. Tier numbers are positions in "order" (or the "tier" fields of an older file without one).
"""
import json
import sys

KINDS = {"base", "home", "city", "starter", "dungeon", "raid", "arena", "battleground"}
FACTIONS = {"alliance", "horde", "deathknight"}


def ordered_tiers(doc: dict) -> list[tuple[int, dict]]:
    """[(tier number, tier)] in priority order: positions in "order", else the "tier" fields."""
    tiers = doc.get("tiers") or []
    order = doc.get("order")
    if order is None:
        return sorted(((int(t["tier"]), t) for t in tiers), key=lambda x: x[0])
    by_key = {}
    for t in tiers:
        k = t.get("key")
        if not isinstance(k, str) or not k:
            raise ValueError("with \"order\", every tier needs a \"key\"")
        if k in by_key:
            raise ValueError(f"tier key {k!r} is used twice")
        by_key[k] = t
    out = []
    for i, k in enumerate(order):
        if k not in by_key:
            raise ValueError(f"order lists {k!r}, but no tier has that key")
        out.append((i, by_key[k]))
    if len(set(order)) != len(order):
        raise ValueError("order lists a key twice")
    return out


def lua_str(s: str) -> str:
    return '"' + str(s).replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def num(v) -> str:
    f = float(v)
    return str(int(f)) if f == int(f) else repr(f)


def tier_lua(n: int, t: dict) -> str:
    kind = t.get("kind") or ("base" if n == 0 else "dungeon")
    if kind not in KINDS:
        raise ValueError(f"tier {n}: unknown kind {kind!r}")
    parts = [f"key = {lua_str(t.get('key', str(n)))}", f"name = {lua_str(t.get('name', ''))}", f"kind = {lua_str(kind)}"]
    fac = t.get("faction")
    if fac:
        if fac not in FACTIONS:
            raise ValueError(f"tier {n}: unknown faction {fac!r}")
        parts.append(f"faction = {lua_str(fac)}")
    maps = []
    for m in t.get("maps") or []:
        e = [f"id = {int(m['id'])}"]
        if m.get("zone") is not None:
            e.append(f"zone = {int(m['zone'])}")
        if m.get("box"):
            b = m["box"]
            if len(b) != 4 or not (b[0] < b[1] and b[2] < b[3]):
                raise ValueError(f"tier {n}: box must be [x min, x max, y min, y max]")
            e.append("box = { " + ", ".join(num(v) for v in b) + " }")
        maps.append("{ " + ", ".join(e) + " }")
    parts.append("maps = { " + ", ".join(maps) + " }")
    play = []
    for p in t.get("play") or []:
        play.append("{ " + ", ".join([lua_str(p["label"]), str(int(p["map"]))] +
                                      [num(p[k]) for k in ("x", "y", "z", "o")] +
                                      ["true" if p.get("raid") else "false"]) + " }")
    if play:
        parts.append("play = { " + ", ".join(play) + " }")
    h = t.get("home")
    if h:
        parts.append("home = { " + ", ".join([str(int(h["map"]))] + [num(h[k]) for k in ("x", "y", "z", "o")]) + " }")
    if t.get("levels"):
        lo, hi = t["levels"]
        parts.append(f"levels = {{ {int(lo)}, {int(hi)} }}")
    if t.get("text"):
        parts.append(f"text = {lua_str(t['text'])}")
    return f"    [{n}] = {{ " + ", ".join(parts) + " },"


def lua(doc: dict) -> str:
    tiers = ordered_tiers(doc)
    if not tiers or tiers[0][0] != 0:
        raise ValueError("the slice has no tier 0")
    low = int((doc.get("lowLevel") or {}).get("level", 15))
    lines = ["-- Generated by tiers_lua.py from slices/" + str(doc.get("slice", "mini")) + ".json: the streamed tiers.",
             "-- ov_slices.lua reads it (OV_STREAM_TIERS). Edit mini.json, not this file.",
             "OV_STREAM_TIERS = {",
             f"    slice = {lua_str(doc.get('slice', 'mini'))},",
             f"    count = {len(tiers)},",
             f"    lowLevel = {low},"]
    lines += [tier_lua(n, t) for n, t in tiers]
    lines.append("}")
    return "\n".join(lines) + "\n"


def main(argv: list[str]) -> int:
    if len(argv) != 1:
        print(__doc__, file=sys.stderr)
        return 2
    with open(argv[0], encoding="utf-8-sig") as f:
        doc = json.load(f)
    try:
        sys.stdout.write(lua(doc))
    except (ValueError, KeyError, TypeError) as e:
        print(f"tiers_lua.py: {argv[0]}: {e}", file=sys.stderr)
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
