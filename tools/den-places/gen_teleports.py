"""The teleports list, written for Den Lite and the in-game Teleports window from one file.

    python3 tools/den-places/gen_teleports.py          # writes both
    python3 tools/den-places/gen_teleports.py --check  # exits 1 when either is out of date (the tests run this)

tools/den-places/teleports.json is the list (owner 4 Nov: "teleport anywhere from the Den, fast"): each place's name,
title, category, other words and where a character stands there (map, x, y, z, facing, the area id when known).
Facts only, no game data: the client draws every place from the player's own files. It writes

- labs/den-lite/src/placelist.rs: the table places.rs includes (`places::PLACES`);
- stream/fui-web/Interface/AddOns/WrathUnleashedUI/TeleportsData.lua: names, titles and categories for the window
  (no coordinates: the window sends `.den go <name>` and Den Lite does the rest).
"""
import json
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
ROOT = HERE.parent.parent
SOURCE = HERE / "teleports.json"
RUST = ROOT / "labs/den-lite/src/placelist.rs"
LUA = ROOT / "stream/fui-web/Interface/AddOns/WrathUnleashedUI/TeleportsData.lua"

# the window's tabs, in order: (category, its title)
CATS = [("city", "Cities"), ("town", "Towns"), ("start", "Starting areas"), ("zone", "Zones"), ("dungeon", "Dungeons"),
        ("raid", "Raids"), ("bg", "Battlegrounds"), ("arena", "Arenas"), ("spot", "Sights"), ("den", "Your Den")]
CAT_IDS = [c[0] for c in CATS]
# words never shown to players (docs/BRAND.md); the legal line is never in a place's title
BANNED = ["world of warcraft", "warcraft", "wow", "lich king", "blizzard"]
NAME = re.compile(r"^[a-z0-9]{1,24}$")
WORD = re.compile(r"^[a-z0-9-]{1,24}$")
EDGE = 17066.0


def load(path=SOURCE):
    doc = json.loads(Path(path).read_text(encoding="utf-8"))
    if doc.get("format") != "leyline-den-teleports":
        raise ValueError("not the teleports list")
    return doc["places"]


def check(places):
    """The list's rules: what Den Lite and the window rely on. A list of problems (empty: fine)."""
    bad = []
    seen = set()
    for p in places:
        n = p.get("name", "")
        if not NAME.match(n):
            bad.append("%r: a name is 1 to 24 lower-case letters and digits" % n)
        if n in seen:
            bad.append("%s: twice" % n)
        seen.add(n)
        if p.get("cat") not in CAT_IDS:
            bad.append("%s: no such category %r" % (n, p.get("cat")))
        for w in p.get("words", []):
            if not WORD.match(w):
                bad.append("%s: word %r" % (n, w))
        t = p.get("title", "")
        if not t or len(t) > 40 or any(c in t for c in '"\\|\n'):
            bad.append("%s: its title" % n)
        low = " %s " % re.sub(r"[^a-z ]", " ", t.lower())
        if any((" %s " % b) in low for b in BANNED):
            bad.append("%s: a word players never see in its title" % n)
        for k in ("x", "y"):
            if not isinstance(p.get(k), (int, float)) or abs(p[k]) >= EDGE:
                bad.append("%s: %s off the map" % (n, k))
        if not isinstance(p.get("z"), (int, float)) or abs(p["z"]) > 5000:
            bad.append("%s: its height" % n)
        if not isinstance(p.get("map"), int) or not 0 <= p["map"] < 1000:
            bad.append("%s: its map" % n)
    return bad


def f(v):
    s = repr(float(v))
    return s if ("." in s or "e" in s) else s + ".0"


def rust(places):
    out = ["// Generated by tools/den-places/gen_teleports.py from tools/den-places/teleports.json: edit that, then run it.",
           "// The places `.den go` / `.go` / the Teleports window know (places.rs includes this as `PLACES`).", "&["]
    for p in places:
        words = ", ".join('"%s"' % w for w in p.get("words", []))
        out.append('    Place { name: "%s", title: "%s", cat: "%s", words: &[%s], map: %d, x: %s, y: %s, z: %s, o: %s, area: %d },'
                   % (p["name"], p["title"], p["cat"], words, p["map"], f(p["x"]), f(p["y"]), f(p["z"]), f(p.get("o", 0)), p.get("area", 0)))
    out.append("]")
    return "\n".join(out) + "\n"


def lua_str(s):
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def lua(places):
    out = ["-- Generated by tools/den-places/gen_teleports.py from tools/den-places/teleports.json: edit that, then run it.",
           "-- The Teleports window's places (Teleports.lua): { name, title, category, other words, map }. No coordinates:",
           "-- the window sends `.den go <name>` and Den Lite (labs/den-lite places.rs) knows where that is.",
           "local W = WrathUnleashedUI",
           "W.TeleportsData = {", "    cats = {"]
    for c, t in CATS:
        out.append("        { %s, %s }," % (lua_str(c), lua_str(t)))
    out.append("    },")
    out.append("    places = {")
    for p in places:
        out.append("        { %s, %s, %s, %s, %d }," % (lua_str(p["name"]), lua_str(p["title"]), lua_str(p["cat"]),
                                                     lua_str(" ".join(p.get("words", []))), p["map"]))
    out.append("    },")
    out.append("}")
    return "\n".join(out) + "\n"


def main(argv):
    places = load()
    bad = check(places)
    if bad:
        print("\n".join(bad))
        return 1
    want = {RUST: rust(places), LUA: lua(places)}
    if "--check" in argv:
        stale = [str(p.relative_to(ROOT)) for p, t in want.items() if not p.is_file() or p.read_text(encoding="utf-8") != t]
        if stale:
            print("out of date: %s (python3 tools/den-places/gen_teleports.py)" % ", ".join(stale))
            return 1
        print("teleports: %d places, both files current" % len(places))
        return 0
    for p, t in want.items():
        p.write_text(t, encoding="utf-8", newline="\n")
    print("teleports: %d places written" % len(places))
    return 0


if __name__ == "__main__":
    sys.exit(main(sys.argv[1:]))
