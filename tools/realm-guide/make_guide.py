#!/usr/bin/env python3
"""The Wrath Unleashed guide, from one source to its two copies.

    python3 tools/realm-guide/make_guide.py          write both copies
    python3 tools/realm-guide/make_guide.py --check  exit 1 when either copy differs from what it would write

Source: docs/realm-guide/wrath-unleashed.json (pages: key, name, icon, heading, lines, commands).
Copies:  docs/leyline/wrath-unleashed.md (the site's notes page, /wrath/docs/wrath-unleashed, stream/docs.py)
         stream/fui-web/Interface/AddOns/WrathUnleashedUI/RealmGuideData.lua (the in-game guide, RealmGuide.lua)
Standard library only.
"""
from __future__ import annotations

import json
import os
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
SRC = os.path.join(ROOT, "docs", "realm-guide", "wrath-unleashed.json")
MD = os.path.join(ROOT, "docs", "leyline", "wrath-unleashed.md")
LUA = os.path.join(ROOT, "stream", "fui-web", "Interface", "AddOns", "WrathUnleashedUI", "RealmGuideData.lua")
BANNED = ("world of warcraft", "warcraft", "lich king", "blizzard")


def load() -> dict:
    with open(SRC, encoding="utf-8") as f:
        return json.load(f)


def check_words(d: dict) -> None:
    import re
    texts = [d["title"], d["intro"]]
    for p in d["pages"]:
        texts += [p["name"], p["heading"], *p["lines"]]
        for c in p["commands"]:
            texts += c
    for t in texts:
        low = t.lower()
        if any(b in low for b in BANNED) or re.search(r"\bwow\b", low):
            raise SystemExit(f"brand word in the guide: {t!r}")


def md(d: dict) -> str:
    out = [f"# {d['title']}", "", d["intro"], ""]
    for p in d["pages"]:
        out += [f"## {p['heading']}", ""]
        out += [f"- {l}" for l in p["lines"]]
        if p["commands"]:
            out += ["", "| Command | What it does |", "|---|---|"]
            out += [f"| `{c}` | {w} |" for c, w in p["commands"]]
        out.append("")
    out += ["Every other command: [Commands](commands.md).", ""]
    return "\n".join(out)


def lua_str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("\n", "\\n") + '"'


def lua(d: dict) -> str:
    out = ["-- Generated by tools/realm-guide/make_guide.py from docs/realm-guide/wrath-unleashed.json: edit that file,",
           "-- then run the script (stream/tests/test_realm_guide.py fails when this copy is stale).",
           "local W = WrathUnleashedUI",
           "if not W then return end",
           f"W.REALM_GUIDE_TITLE = {lua_str(d['title'])}",
           "W.REALM_GUIDE = {"]
    for p in d["pages"]:
        out.append(f"    {{ key = {lua_str(p['key'])}, name = {lua_str(p['name'])}, icon = {lua_str(p['icon'])}, "
                   f"heading = {lua_str(p['heading'])},")
        out.append("      lines = {")
        out += [f"        {lua_str(l)}," for l in p["lines"]]
        out.append("      },")
        out.append("      commands = {")
        out += [f"        {{ {lua_str(c)}, {lua_str(w)} }}," for c, w in p["commands"]]
        out.append("      } },")
    out.append("}")
    return "\n".join(out) + "\n"


def main() -> int:
    d = load()
    check_words(d)
    want = {MD: md(d), LUA: lua(d)}
    if "--check" in sys.argv:
        stale = []
        for path, text in want.items():
            try:
                with open(path, encoding="utf-8") as f:
                    if f.read() != text:
                        stale.append(path)
            except OSError:
                stale.append(path)
        for s in stale:
            print("stale:", os.path.relpath(s, ROOT))
        return 1 if stale else 0
    for path, text in want.items():
        with open(path, "w", encoding="utf-8", newline="\n") as f:
            f.write(text)
        print("wrote", os.path.relpath(path, ROOT))
    return 0


if __name__ == "__main__":
    sys.exit(main())
